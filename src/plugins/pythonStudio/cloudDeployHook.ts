/**
 * plugins/pythonStudio/cloudDeployHook.ts
 *
 * Bridge to Evolve AI's Cloud Hub and Pilot Deployment Engine.
 * Responsibilities:
 *  - Discovers active enterprise cloud credentials (GCP, AWS, Azure, Databricks)
 *  - Injects cloud tokens into the local Python sandbox execution environment
 *  - Scaffolds multi-stage, secure Dockerfiles optimized for Python & AI
 *  - Generates deployment descriptors matching the Delivery Studio target VPC
 */

import * as path   from 'path';
import * as fs     from 'fs';

export type TargetCloudVpc = 'gcp-firebase' | 'aws' | 'azure' | 'docker' | 'databricks';

export interface CloudCredentialStatus {
  gcpActive: boolean;
  gcpProject?: string;
  awsActive: boolean;
  awsProfile?: string;
  azureActive: boolean;
  databricksActive: boolean;
}

export class CloudDeployHook {
  /**
   * Discovers active cloud authentication configurations from the developer environment.
   */
  static inspectActiveCloudCredentials(): CloudCredentialStatus {
    const env = process.env;
    const home = process.env.HOME || process.env.USERPROFILE || '';

    // GCP detection
    const gcpCredsPath = env.GOOGLE_APPLICATION_CREDENTIALS || path.join(home, '.config', 'gcloud', 'application_default_credentials.json');
    const gcpActive = fs.existsSync(gcpCredsPath) || Boolean(env.CLOUDSDK_CORE_PROJECT);

    // AWS detection
    const awsCredsPath = path.join(home, '.aws', 'credentials');
    const awsActive = fs.existsSync(awsCredsPath) || Boolean(env.AWS_ACCESS_KEY_ID || env.AWS_PROFILE);

    // Azure detection
    const azProfilePath = path.join(home, '.azure', 'azureProfile.json');
    const azureActive = fs.existsSync(azProfilePath) || Boolean(env.AZURE_CLIENT_ID);

    // Databricks detection
    const databricksCfg = path.join(home, '.databrickscfg');
    const databricksActive = fs.existsSync(databricksCfg) || Boolean(env.DATABRICKS_HOST);

    return {
      gcpActive,
      gcpProject: env.CLOUDSDK_CORE_PROJECT,
      awsActive,
      awsProfile: env.AWS_PROFILE || 'default',
      azureActive,
      databricksActive,
    };
  }

  /**
   * Builds an environment variable map with active cloud tokens for the Python execution sandbox.
   */
  static getSandboxEnvironment(): Record<string, string> {
    const envCopy: Record<string, string> = {};
    const creds = this.inspectActiveCloudCredentials();

    if (creds.gcpActive) {
      if (process.env.GOOGLE_APPLICATION_CREDENTIALS) {
        envCopy['GOOGLE_APPLICATION_CREDENTIALS'] = process.env.GOOGLE_APPLICATION_CREDENTIALS;
      }
      if (process.env.CLOUDSDK_CORE_PROJECT) {
        envCopy['CLOUDSDK_CORE_PROJECT'] = process.env.CLOUDSDK_CORE_PROJECT;
      }
    }

    if (creds.awsActive) {
      if (process.env.AWS_PROFILE) envCopy['AWS_PROFILE'] = process.env.AWS_PROFILE;
      if (process.env.AWS_REGION)  envCopy['AWS_REGION']  = process.env.AWS_REGION;
    }

    if (creds.azureActive) {
      if (process.env.AZURE_TENANT_ID) envCopy['AZURE_TENANT_ID'] = process.env.AZURE_TENANT_ID;
    }

    if (creds.databricksActive) {
      if (process.env.DATABRICKS_HOST)  envCopy['DATABRICKS_HOST']  = process.env.DATABRICKS_HOST;
      if (process.env.DATABRICKS_TOKEN) envCopy['DATABRICKS_TOKEN'] = process.env.DATABRICKS_TOKEN;
    }

    return envCopy;
  }

  /**
   * Generates a high-performance, hardened multi-stage Dockerfile for Python AI applications.
   * Leverages official python:3.12-slim base, non-root user, and uv dependency caching.
   */
  static generateHardenedDockerfile(serviceName: string, entrypointModule = 'main:app'): string {
    return `# ==============================================================================
# Multi-Stage Hardened Container for Python AI Service: ${serviceName}
# Generated by Evolve AI Delivery Studio (Python AI Studio Plugin)
# ==============================================================================

# ── Stage 1: Build & Dependency Resolution ────────────────────────────────────
FROM python:3.12-slim AS builder

WORKDIR /build

# Install uv for ultra-fast dependency compilation
COPY --from=ghcr.io/astral-sh/uv:latest /uv /bin/uv

# Copy dependency manifests
COPY pyproject.toml requirements*.txt* ./

# Compile wheels into isolated directory with cache mount
RUN --mount=type=cache,target=/root/.cache/uv \\
    if [ -f requirements.txt ]; then \\
        uv pip install --system --target /opt/venv-packages -r requirements.txt; \\
    elif [ -f pyproject.toml ]; then \\
        uv pip install --system --target /opt/venv-packages .; \\
    fi

# ── Stage 2: Minimal Distroless / Hardened Runtime ────────────────────────────
FROM python:3.12-slim AS runtime

# Security: Create non-root unprivileged service account
RUN groupadd -r appgroup && useradd -r -g appgroup -d /app -s /sbin/nologin appuser

WORKDIR /app

# Copy compiled packages from builder
COPY --from=builder /opt/venv-packages /usr/local/lib/python3.12/site-packages/

# Copy application source code
COPY . /app

# Environment variables for Python production
ENV PYTHONUNBUFFERED=1 \\
    PYTHONDONTWRITEBYTECODE=1 \\
    PORT=8080

EXPOSE 8080

USER appuser

# Health check
HEALTHCHECK --interval=30s --timeout=5s --start-period=5s --retries=3 \\
    CMD python -c "import urllib.request; urllib.request.urlopen('http://localhost:8080/healthz')" || exit 1

CMD ["python", "-m", "uvicorn", "${entrypointModule}", "--host", "0.0.0.0", "--port", "8080"]
`;
  }

  /**
   * Generates a unified multi-stage Dockerfile that builds a modern SPA frontend (React/Vite)
   * and bundles it with the FastAPI / Python AI backend in a single hardened, production container.
   */
  static generateFullStackDockerfile(serviceName: string, entrypointModule = 'main:app'): string {
    return `# ==============================================================================
# Unified Multi-Stage Production Container: ${serviceName}
# Frontend SPA (React/Vite) + Backend API & RAG Engine (FastAPI/Python 3.12)
# Generated by Evolve AI Delivery Studio (Python AI Studio & Neural Debugger)
# ==============================================================================

# ── Stage 1: Frontend SPA Asset Compilation ──────────────────────────────────
FROM node:20-alpine AS frontend-builder
WORKDIR /app/frontend
COPY frontend/package*.json ./
RUN npm ci --prefer-offline || npm install
COPY frontend/ ./
RUN npm run build

# ── Stage 2: Python Backend Dependency Resolution (uv) ────────────────────────
FROM python:3.12-slim AS backend-builder
WORKDIR /build
COPY --from=ghcr.io/astral-sh/uv:latest /uv /bin/uv
COPY backend/pyproject.toml* backend/requirements*.txt* ./
RUN --mount=type=cache,target=/root/.cache/uv \
    if [ -f requirements.txt ]; then \
        uv pip install --system --target /opt/venv-packages -r requirements.txt; \
    elif [ -f pyproject.toml ]; then \
        uv pip install --system --target /opt/venv-packages .; \
    fi

# ── Stage 3: Minimal Hardened Production Runtime ───────────────────────────────
FROM python:3.12-slim AS runtime
RUN groupadd -r appgroup && useradd -r -g appgroup -d /app -s /sbin/nologin appuser
WORKDIR /app

# Copy compiled backend packages
COPY --from=backend-builder /opt/venv-packages /usr/local/lib/python3.12/site-packages/

# Copy backend source code & create persistent storage directory
COPY backend/ /app/
RUN mkdir -p /app/data && chown -R appuser:appgroup /app/data

# Copy compiled frontend assets to static distribution folder
COPY --from=frontend-builder /app/frontend/dist /app/static

ENV PYTHONUNBUFFERED=1 \
    PYTHONDONTWRITEBYTECODE=1 \
    PORT=8080 \
    STATIC_DIR=/app/static \
    DATA_DIR=/app/data

EXPOSE 8080
USER appuser

HEALTHCHECK --interval=30s --timeout=5s --start-period=5s --retries=3 \
    CMD python -c "import urllib.request; urllib.request.urlopen('http://localhost:8080/healthz')" || exit 1

CMD ["python", "-m", "uvicorn", "${entrypointModule}", "--host", "0.0.0.0", "--port", "8080"]
`;
  }

  /**
   * Generates a turnkey docker-compose.yml configuration with persistent volumes and healthchecks.
   */
  static generateFullStackDockerCompose(serviceName: string): string {
    return `version: '3.8'

services:
  app:
    build:
      context: .
      dockerfile: Dockerfile
    container_name: ${serviceName}
    ports:
      - "8080:8080"
    environment:
      - PYTHONUNBUFFERED=1
      - ENVIRONMENT=local
      - GEMINI_API_KEY=\${GEMINI_API_KEY}
      - DATABASE_URL=sqlite:////app/data/app.db
      - CHROMA_PERSIST_DIR=/app/data/chroma
    volumes:
      - app-data:/app/data
    restart: unless-stopped
    healthcheck:
      test: ["CMD", "python", "-c", "import urllib.request; urllib.request.urlopen('http://localhost:8080/healthz')"]
      interval: 15s
      timeout: 5s
      retries: 3
      start_period: 10s

volumes:
  app-data:
    driver: local
`;
  }

  /**
   * Generates a 1-click cloud pilot deploy runbook snippet for the target VPC.
   */
  static generateDeployRunbookSnippet(targetVpc: TargetCloudVpc, serviceName: string): string {
    switch (targetVpc) {
      case 'gcp-firebase':
        return `# ── GCP Cloud Run Deploy ──────────────────────────────────────────────────
gcloud run deploy ${serviceName} \\
    --source . \\
    --region us-central1 \\
    --allow-unauthenticated \\
    --memory 2Gi \\
    --cpu 2 \\
    --set-env-vars PYTHONUNBUFFERED=1
`;
      case 'aws':
        return `# ── AWS App Runner & ECR Production Deploy ──────────────────────────────
# Step 1: AWS Environment Configuration
export AWS_REGION="\${AWS_REGION:-us-east-1}"
export AWS_ACCOUNT_ID=$(aws sts get-caller-identity --query Account --output text)
export ECR_REPO="${serviceName}"
export IMAGE_URI="\${AWS_ACCOUNT_ID}.dkr.ecr.\${AWS_REGION}.amazonaws.com/\${ECR_REPO}:latest"

# Step 2: Authenticate Docker with Amazon ECR & Create Repository if needed
aws ecr get-login-password --region \${AWS_REGION} | docker login --username AWS --password-stdin \${AWS_ACCOUNT_ID}.dkr.ecr.\${AWS_REGION}.amazonaws.com
aws ecr describe-repositories --repository-names \${ECR_REPO} --region \${AWS_REGION} 2>/dev/null || \\
    aws ecr create-repository --repository-name \${ECR_REPO} --region \${AWS_REGION}

# Step 3: Build, Tag & Push Multi-Stage Container
docker build -t \${ECR_REPO}:latest .
docker tag \${ECR_REPO}:latest \${IMAGE_URI}
docker push \${IMAGE_URI}

# Step 4: Deploy Service on AWS App Runner
aws apprunner create-service \\
    --service-name ${serviceName} \\
    --source-configuration '{
        "ImageRepository": {
            "ImageIdentifier": "'"\${IMAGE_URI}"'",
            "ImageConfiguration": {
                "Port": "8080",
                "RuntimeEnvironmentVariables": {
                    "PYTHONUNBUFFERED": "1",
                    "ENVIRONMENT": "production"
                }
            },
            "ImageRepositoryType": "ECR"
        },
        "AutoDeploymentsEnabled": true
    }' \\
    --instance-configuration '{"Cpu": "1 vCPU", "Memory": "2 GB"}' \\
    --health-check-configuration '{"Path": "/healthz", "Protocol": "HTTP", "Interval": 10, "Timeout": 5}'
`;
      case 'azure':
        return `# ── Azure Container Apps Deploy ─────────────────────────────────────────
az containerapp up \\
    --name ${serviceName} \\
    --source . \\
    --ingress external \\
    --target-port 8080
`;
      default:
        return `# ── Local / Docker Compose Pilot ─────────────────────────────────────────
docker build -t ${serviceName}:pilot .
docker run -p 8080:8080 --rm ${serviceName}:pilot
`;
    }
  }
}
