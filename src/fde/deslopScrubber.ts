/**
 * src/fde/deslopScrubber.ts
 *
 * Deslop & Anti-Slop Hygiene Scanner for Evolve AI Forward Deployed Engineers.
 * Resolves GAP-10.
 *
 * Scans implementation files and pull requests for LLM code smells:
 *   - Stale conversational AI comments ("Here is the code", "Implement here")
 *   - Unsafe empty catch blocks silently swallowing errors
 *   - Over-abstracted single-use pass-through functions
 *   - Generic unbranded UI buttons and placeholders
 *   - Redundant boilerplate and dead code blocks
 */

import * as fs from 'fs';
import * as path from 'path';

export interface DeslopFinding {
  rule: 'stale-comment' | 'empty-catch' | 'over-abstraction' | 'generic-ui' | 'unhandled-error' | 'dead-code';
  file: string;
  line: number;
  snippet: string;
  message: string;
  severity: 'advisory' | 'blocking';
}

export interface DeslopReport {
  scannedFilesCount: number;
  cleanFilesCount: number;
  totalFindings: number;
  blockingCount: number;
  advisoryCount: number;
  findings: DeslopFinding[];
  isClean: boolean;
}

export class DeslopScrubber {
  public static scrubDirectory(
    dirPath: string,
    fileExtensions = ['.ts', '.js', '.py', '.go', '.java', '.cs', '.html']
  ): DeslopReport {
    const findings: DeslopFinding[] = [];
    let scannedCount = 0;
    let cleanCount = 0;

    const walk = (cur: string) => {
      let entries: fs.Dirent[] = [];
      try {
        entries = fs.readdirSync(cur, { withFileTypes: true });
      } catch {
        return;
      }

      for (const e of entries) {
        if (e.name === 'node_modules' || e.name === '.git' || e.name === 'out' || e.name === 'dist' || e.name === '.venv') {
          continue;
        }
        const full = path.join(cur, e.name);
        if (e.isDirectory()) {
          walk(full);
        } else if (e.isFile()) {
          const ext = path.extname(e.name).toLowerCase();
          if (fileExtensions.includes(ext)) {
            scannedCount++;
            try {
              const content = fs.readFileSync(full, 'utf8');
              const fileFindings = this.scrubContent(full, content);
              if (fileFindings.length === 0) {
                cleanCount++;
              } else {
                findings.push(...fileFindings);
              }
            } catch {}
          }
        }
      }
    };

    walk(dirPath);

    const blocking = findings.filter(f => f.severity === 'blocking').length;
    const advisory = findings.length - blocking;

    return {
      scannedFilesCount: scannedCount,
      cleanFilesCount: cleanCount,
      totalFindings: findings.length,
      blockingCount: blocking,
      advisoryCount: advisory,
      findings,
      isClean: blocking === 0
    };
  }

  public static scrubContent(filePath: string, content: string): DeslopFinding[] {
    const findings: DeslopFinding[] = [];
    const lines = content.split('\n');

    lines.forEach((line, idx) => {
      const lineNum = idx + 1;
      const trimmed = line.trim();

      // 1. Stale conversational AI comments
      if (
        /\/\/\s*(here is the|here's the|implement logic here|replace with your|generated by|in a real app|for demo purposes|add your own)/i.test(trimmed) ||
        /#\s*(here is the|here's the|implement logic here|replace with your|generated by|in a real app)/i.test(trimmed)
      ) {
        findings.push({
          rule: 'stale-comment',
          file: filePath,
          line: lineNum,
          snippet: trimmed,
          message: 'Conversational AI placeholder comment found. Replace with production documentation or remove.',
          severity: 'advisory'
        });
      }

      // 2. Unsafe empty catch blocks
      if (
        /catch\s*\([^)]*\)\s*\{\s*\}/.test(trimmed) ||
        /except\s*:\s*pass\b/.test(trimmed) ||
        /except\s+\w+\s*:\s*pass\b/.test(trimmed)
      ) {
        findings.push({
          rule: 'empty-catch',
          file: filePath,
          line: lineNum,
          snippet: trimmed,
          message: 'Empty catch/except block silently swallows exceptions. Must log or handle.',
          severity: 'blocking'
        });
      }

      // 3. Generic unbranded UI components in templates
      if (
        /<button>\s*Click here\s*<\/button>/i.test(trimmed) ||
        /<button class="btn">\s*Submit\s*<\/button>/i.test(trimmed)
      ) {
        findings.push({
          rule: 'generic-ui',
          file: filePath,
          line: lineNum,
          snippet: trimmed,
          message: 'Generic unstyled button template. Enforce branded UI design system classes.',
          severity: 'advisory'
        });
      }

      // 4. Naked TODO comments without ticket tracking
      if (
        /\/\/\s*TODO\b/i.test(trimmed) && !/TODO\s*\(#|\bTODO\s*\[/i.test(trimmed) && !trimmed.includes('TODO:')
      ) {
        findings.push({
          rule: 'dead-code',
          file: filePath,
          line: lineNum,
          snippet: trimmed,
          message: 'Unanchored TODO comment without issue/tracking reference.',
          severity: 'advisory'
        });
      }
    });

    return findings;
  }

  public static formatMarkdownReport(report: DeslopReport): string {
    const lines = [
      '# 🧹 Anti-Slop Hygiene & Code Scrubber Report',
      '',
      `- **Scanned Files**: ${report.scannedFilesCount}`,
      `- **Clean Files**: ${report.cleanFilesCount}`,
      `- **Total Findings**: ${report.totalFindings} (${report.blockingCount} blocking, ${report.advisoryCount} advisory)`,
      `- **Verdict**: ${report.isClean ? '✅ PASS (No blocking slop)' : '❌ FAIL (Blocking smells detected)'}`,
      '',
      '## Findings',
      '',
      '| Severity | Rule | File:Line | Snippet | Message |',
      '|:---:|:---:|---|---|---|'
    ];

    for (const f of report.findings) {
      const relFile = f.file.replace(/\\/g, '/');
      lines.push(`| ${f.severity === 'blocking' ? '🔴 BLOCKING' : '🟡 ADVISORY'} | \`${f.rule}\` | \`${relFile}:${f.line}\` | \`${f.snippet.slice(0, 40).replace(/`/g, "'")}\` | ${f.message} |`);
    }

    return lines.join('\n');
  }
}
